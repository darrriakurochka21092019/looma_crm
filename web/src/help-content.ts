export function guidesForRole(role: Role) {
  return helpGuides.filter((g) => g.roles.includes(role));
}
export function stepsForGuide(guide: HelpGuide, role: Role) {
  return guide.steps.filter((step) => !step.roles || step.roles.includes(role));
}
export function contextualGuide(
  route: string,
  modal: string | undefined,
  settingsTab = 'company',
): HelpGuideId {
  if (modal === 'profile') return 'profile';
  if (modal === 'import') return 'import';
  const form = helpGuides.find((g) => g.contextOnly && g.modal === modal);
  if (form) return form.id;
  if (route.startsWith('orders/')) return 'order';
  const root = route.split(/[/?]/)[0];
  if (root === 'settings')
    return (
      ['company', 'team', 'max', 'template', 'import', 'backup', 'audit'].includes(settingsTab)
        ? settingsTab
        : 'company'
    ) as HelpGuideId;
  return (
    ['dashboard', 'orders', 'clients', 'finance', 'tasks', 'documents', 'reports'].includes(root)
      ? root
      : 'workspace'
  ) as HelpGuideId;
}

