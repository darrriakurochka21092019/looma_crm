import type { Role } from '../../shared/domain';
import type { HelpGuideId } from '../../shared/help';

export type HelpStep = {
  id: string;
  title: string;
  text: string;
  target: string;
  tab?: string;
  roles?: Role[];
};
export type HelpGuide = {
  id: HelpGuideId;
  title: string;
  description: string;
  route?: string;
  modal?: string;
  order?: boolean;
  roles: Role[];
  steps: HelpStep[];
  contextOnly?: boolean;
};
const all: Role[] = ['owner', 'manager', 'accountant', 'master'];
const finance: Role[] = ['owner', 'manager', 'accountant'];
const commercial: Role[] = ['owner', 'manager'];
const owner: Role[] = ['owner'];
const s = (
  id: string,
  title: string,
  text: string,
  target: string,
  extra: Partial<HelpStep> = {},
): HelpStep => ({ id, title, text, target, ...extra });
const settingsGuide = (
  id: HelpGuideId,
  title: string,
  description: string,
  tab: string,
  steps: HelpStep[],
): HelpGuide => ({
  id,
  title,
  description,
  roles: owner,
  route: 'settings',
  steps: steps.map((step) => ({ ...step, tab: 'settings:' + tab })),
});

